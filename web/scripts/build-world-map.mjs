// Builds src/content/world-map.ts, the support network's map (0.170.0,
// docs/support-network.md). Run once by hand; its output is committed and
// nothing here runs at build or at request time.
//
// The source is Natural Earth's admin-0 countries in the **India point of
// view** edition — India's boundary as India claims it, which for an Indian
// client is a legal matter, not a style — public domain
// (https://www.naturalearthdata.com/about/terms-of-use/):
//
//   curl -L -o ind10.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries_ind.geojson
//   npx mapshaper@0.6 ind10.geojson -filter 'CONTINENT != "Antarctica"' \
//     -filter-fields ISO_A2_EH,NAME_EN -simplify 0.9% keep-shapes \
//     -proj +proj=mill -o format=geojson precision=1000 world.json
//   node scripts/build-world-map.mjs world.json
//
// The output is drawn 1000 units wide. `project()` in the generated module is
// the same Miller arithmetic, so a pin and an outline always agree.
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) { console.error("usage: node scripts/build-world-map.mjs world.json"); process.exit(1); }
const geo = JSON.parse(readFileSync(src, "utf8"));

const R = 6378137;
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
const each = (f) => {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) for (const ring of poly) for (const [x, y] of ring) {
    if (x < minX) minX = x; if (x > maxX) maxX = x; if (y < minY) minY = y; if (y > maxY) maxY = y;
  }
};
geo.features.filter((f) => f.geometry).forEach(each);

const WIDTH = 1000;
const k = WIDTH / (maxX - minX);
const HEIGHT = Math.round((maxY - minY) * k);
const r1 = (n) => Math.round(n * 10) / 10;
const sx = (x) => (x - minX) * k;
const sy = (y) => (maxY - y) * k;

const countries = [];
for (const f of geo.features) {
  if (!f.geometry) continue;
  const code = f.properties.ISO_A2_EH && f.properties.ISO_A2_EH !== "-99" ? f.properties.ISO_A2_EH : "";
  const name = f.properties.NAME_EN;
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  let d = "";
  let bx0 = Infinity, by0 = Infinity, bx1 = -Infinity, by1 = -Infinity;
  for (const poly of polys) for (const ring of poly) {
    let px = 0, py = 0;
    ring.forEach(([x, y], i) => {
      const X = r1(sx(x)), Y = r1(sy(y));
      if (X < bx0) bx0 = X; if (X > bx1) bx1 = X; if (Y < by0) by0 = Y; if (Y > by1) by1 = Y;
      if (i === 0) d += `M${X} ${Y}`;
      else {
        const dx = r1(X - px), dy = r1(Y - py);
        if (dx || dy) d += `l${dx} ${dy}`.replace(/ -/g, "-");
      }
      px = X; py = Y;
    });
    d += "z";
  }
  countries.push({ code, name, d, box: [r1(bx0), r1(by0), r1(bx1 - bx0), r1(by1 - by0)] });
}
countries.sort((a, b) => a.name.localeCompare(b.name));

const out = `// Generated by scripts/build-world-map.mjs from Natural Earth's admin-0
// countries, India point-of-view edition (public domain). Do not edit by
// hand: change the script and run it again. docs/support-network.md.

/** The map's own size: drawn into \`viewBox="0 0 \${MAP_WIDTH} \${MAP_HEIGHT}"\`. */
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

export type MapCountry = {
  /** ISO 3166-1 alpha-2, or "" for a territory without one. */
  code: string;
  name: string;
  /** The SVG path, in map units. */
  d: string;
  /** Its bounding box in map units: x, y, width, height. */
  box: [number, number, number, number];
};

export const COUNTRIES: MapCountry[] = ${JSON.stringify(countries)};

const R = ${R};
const MIN_X = ${minX};
const MAX_Y = ${maxY};
const K = ${k};

/**
 * Latitude and longitude to map units — the Miller projection the outlines
 * were drawn with, so a pin and its country always agree.
 */
export function project(lat: number, lng: number): { x: number; y: number } {
  const phi = (Math.max(-85, Math.min(85, lat)) * Math.PI) / 180;
  const lambda = (lng * Math.PI) / 180;
  const x = R * lambda;
  const y = R * 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * phi));
  return { x: (x - MIN_X) * K, y: (MAX_Y - y) * K };
}

/** Map units back to latitude and longitude, for the console's click-to-place. */
export function unproject(px: number, py: number): { lat: number; lng: number } {
  const x = px / K + MIN_X;
  const y = MAX_Y - py / K;
  const lng = (x / R) * (180 / Math.PI);
  const phi = (Math.atan(Math.exp(y / (R * 1.25))) - Math.PI / 4) / 0.4;
  return { lat: Math.round(phi * (180 / Math.PI) * 1e6) / 1e6, lng: Math.round(lng * 1e6) / 1e6 };
}
`;
writeFileSync(new URL("../src/content/world-map.ts", import.meta.url), out);
console.log(`Wrote ${countries.length} countries, ${WIDTH} × ${HEIGHT}, ${Math.round(out.length / 1024)} KB.`);
