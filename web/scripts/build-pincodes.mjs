/**
 * Generates `src/lib/pincode-data.ts` — the PIN code table the delivery
 * address form fills itself from.
 *
 * ## Why the data is vendored rather than depended on
 *
 * Every published Indian pincode package is one of two things: a small one
 * that is wrong, or a large one that is slow. `pincode-lookup` is 68KB gzipped
 * and maps `110025` — Jamia Nagar, Delhi — to **Budaun in Uttar Pradesh**, and
 * it is seven weeks old with one version and one maintainer, which is not what
 * you want between a customer and a checkout in a public repository.
 * `india-pincode-lookup` has the right answer and is 18MB of JSON scanned
 * linearly with `Array.filter` on every lookup.
 *
 * So the second one's data is reduced, once, to the ~19.5k unique PIN codes
 * this form needs and committed. No runtime dependency, no third-party request
 * with a customer's PIN code in it, nothing that can be swapped under us by a
 * future version, and the whole table is a file somebody can read.
 *
 * ## Regenerating
 *
 *     cd web
 *     npm i --no-save india-pincode-lookup       # ~18MB, not kept
 *     node scripts/build-pincodes.mjs
 *     npm uninstall india-pincode-lookup
 *
 * Or pass a path to any JSON array of India Post records carrying
 * `pincode`, `districtName`, `stateName` and `taluk`:
 *
 *     node scripts/build-pincodes.mjs ./some-postal-directory.json
 *
 * The underlying source either way is India Post's own postal directory,
 * which is public data and changes a few times a year.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const arg = process.argv[2];
const rows = arg
  ? JSON.parse(readFileSync(arg, "utf8"))
  : createRequire(import.meta.url)("india-pincode-lookup/pincodes.json");

/**
 * ALL CAPS becomes Title Case; anything already mixed is left alone.
 *
 * The source is inconsistent about it — `stateName` is "WEST BENGAL" and
 * `districtName` is "North 24 Parganas" — and an address field shouting at
 * somebody is a form that looks broken. Words already carrying a lower-case
 * letter are somebody's deliberate spelling and are not touched.
 */
function titleCase(value) {
  const s = clean(value);
  if (!s || /[a-z]/.test(s)) return s;
  return s
    .toLowerCase()
    .replace(/(^|[\s(/-])([a-z])/g, (_, before, letter) => before + letter.toUpperCase());
}

/**
 * A place name, with the characters that would break this file taken out.
 *
 * `|` and `;` are the table's own delimiters, and a backtick would end the
 * template literal the table is emitted into. One row in the source really
 * does carry a stray backtick in a taluk name, and it took `tsc` to find it:
 * this is a government directory typed by many hands over many years, so it
 * is treated as hostile input rather than as data that happens to be well
 * formed. Control characters go for the same reason a newline would.
 */
function clean(value) {
  return String(value ?? "")
    .replace(/[`|;\\]/g, " ")
    .replace(/[\u0000-\u001f\u007f]/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

const byPin = new Map();

for (const row of rows) {
  const pin = String(row.pincode ?? "").padStart(6, "0");
  if (!/^[1-9][0-9]{5}$/.test(pin)) continue;

  const entry = byPin.get(pin) ?? { states: new Set(), districts: new Set(), places: new Set() };
  const state = titleCase(row.stateName);
  const district = titleCase(row.districtName);
  const taluk = titleCase(row.taluk);

  if (state) entry.states.add(state);
  if (district) entry.districts.add(district);
  // "NA" is how this source spells "no taluk recorded", and a taluk that only
  // repeats the district is not a second suggestion.
  if (taluk && taluk.toUpperCase() !== "NA" && taluk !== district) entry.places.add(taluk);

  byPin.set(pin, entry);
}

const lines = [];
for (const pin of [...byPin.keys()].sort()) {
  const { states, districts, places } = byPin.get(pin);
  lines.push([pin, [...states].join(";"), [...districts].join(";"), [...places].join(";")].join("|"));
}

const multi = [...byPin.values()].filter((e) => e.districts.size > 1).length;

const out = `// GENERATED by scripts/build-pincodes.mjs — do not edit by hand.
//
// One line per PIN code: pincode|state(s)|district(s)|other place names.
// Multiple values are separated by ";" — around ${multi.toLocaleString("en-IN")}
// PIN codes straddle a district boundary, which is why the form offers the
// alternatives rather than picking one and pretending.
//
// Derived from India Post's postal directory. Public data; see the generator
// for provenance and how to rebuild it.
//
// ${byPin.size.toLocaleString("en-IN")} PIN codes, from ${rows.length.toLocaleString("en-IN")} post office records.

export const PINCODE_TABLE = \`${lines.join("\n")}\`;
`;

writeFileSync("src/lib/pincode-data.ts", out);
console.log(`${byPin.size} pincodes from ${rows.length} records`);
console.log(`${multi} straddle more than one district`);
console.log(`src/lib/pincode-data.ts — ${(out.length / 1024).toFixed(0)} KB`);
